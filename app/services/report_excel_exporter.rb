# frozen_string_literal: true

require "caxlsx"

# Data comes first so an exported report is ready to filter or pivot immediately.
# Explicit column types preserve identifiers and make amounts usable in Excel.
class ReportExcelExporter
  class << self
    def generate(report)
      result = report.result_data.deep_symbolize_keys
      columns = report.result_columns
      package = Axlsx::Package.new
      workbook = package.workbook
      workbook.escape_formulas = true
      styles = build_styles(workbook)

      add_data_sheet(workbook, "Data", columns, result[:table] || [], styles)
      if result[:held_orders_table].present?
        add_data_sheet(workbook, "Held orders", columns, result[:held_orders_table], styles)
      end
      # @type var additional_tables: Array[Hash[Symbol, untyped]]
      additional_tables = Array(result[:additional_tables])
      additional_tables.each do |table|
        add_data_sheet(workbook, table[:name], table[:columns], table[:rows], styles)
      end
      add_summary_sheet(workbook, report, result, styles)

      stream = package.to_stream or raise "Could not serialize report export"
      stream.read or raise "Could not read report export"
    end

    private

      def build_styles(workbook)
        formats = {
          string: "@", integer: "#,##0", currency: "$#,##0.00;[Red]-$#,##0.00",
          percentage: "0.0%", date: "yyyy-mm-dd", datetime: "yyyy-mm-dd hh:mm"
        }
        formats.to_h { |key, format| [ key, workbook.styles.add_style(format_code: format, sz: 11) ] }
          .merge(header: workbook.styles.add_style(b: true, bg_color: "214E47", fg_color: "FFFFFF", sz: 11))
      end

      def add_data_sheet(workbook, name, columns, rows, styles)
        # Excel has a hard row limit. Split full results into numbered sheets
        # rather than dropping rows or returning a corrupt workbook.
        rows.each_slice(1_048_575).with_index do |batch, index|
          sheet_name = index.zero? ? name : "#{name} #{index + 1}"
          write_data_sheet(workbook, sheet_name, columns, batch, styles)
        end
        write_data_sheet(workbook, name, columns, [], styles) if rows.empty?
      end

      def write_data_sheet(workbook, name, columns, rows, styles)
        workbook.add_worksheet(name: name) do |sheet|
          sheet.add_row columns.map { |column| column[:label] }, types: :string, style: styles[:header]
          rows.each do |row|
            row = row.symbolize_keys
            cells = columns.map { |column| typed_cell(row[column[:key].to_sym], column[:type]) }
            sheet.add_row cells.map(&:first), types: cells.map(&:last),
              style: columns.map { |column| styles.fetch((column[:type] || :string).to_sym, styles[:string]) }
          end
          unless columns.empty?
            reference = "A1:#{Axlsx.col_ref(columns.size - 1)}#{rows.size + 1}"
            if rows.any?
              sheet.add_table(reference, name: "ReportData#{workbook.worksheets.size}", style_info: { name: "TableStyleMedium2", show_row_stripes: true })
            else
              sheet.auto_filter = reference
            end
          end
          sheet.sheet_view.pane { |pane| pane.state = :frozen; pane.y_split = 1; pane.top_left_cell = "A2"; pane.active_pane = :bottom_left }
          sheet.column_widths(*columns.map { |column| [ [ column[:label].length + 4, 18 ].max, 40 ].min })
        end
      end

      def typed_cell(value, type)
        return [ nil, :string ] if value.nil? || value == ""

        case type.to_s
        when "currency" then [ BigDecimal(value.to_s.delete("$,")), :float ]
        when "integer" then [ Integer(value.to_s, 10), :integer ]
        when "percentage" then [ BigDecimal(value.to_s.delete("%")) / 100, :float ]
        when "date" then [ Date.parse(value.to_s), :date ]
        when "datetime" then [ Time.zone.parse(value.to_s), :time ]
        else [ value.to_s, :string ]
        end
      rescue ArgumentError, TypeError
        # Old snapshots can contain placeholders (e.g. an em dash). Keep the
        # original value instead of converting missing data into a false zero.
        [ value.to_s, :string ]
      end

      def add_summary_sheet(workbook, report, result, styles)
        workbook.add_worksheet(name: "Summary") do |sheet|
          sheet.add_row [ "Report", report.title ], types: :string, style: styles[:header]
          metadata = {
            "Type" => report.template&.title || report.report_type,
            "Generated" => report.completed_at&.strftime("%Y-%m-%d %H:%M"),
            "Generated by" => report.generated_by.name.presence || report.generated_by.email_address,
            "Data rows" => Array(result[:table]).size.to_s
          }
          metadata.each { |key, value| sheet.add_row [ key, value ], types: :string }
          sheet.add_row []
          sheet.add_row [ "Settings" ], types: :string, style: styles[:header]
          report.parameters.each { |key, value| sheet.add_row [ key.to_s.titleize, Array(value).join(", ") ], types: :string }
          sheet.add_row []
          sheet.add_row [ "Summary" ], types: :string, style: styles[:header]
          (result[:summary] || {}).each { |key, value| sheet.add_row [ key.to_s.titleize, value.to_s ], types: :string }
          sheet.add_row []
          sheet.add_row [ "Working in Excel", "Use the Data sheet filters, SUM, or Insert > PivotTable. This is a saved snapshot; generate a new report for updated data." ], types: :string
          sheet.column_widths 28, 80
        end
      end
  end
end
